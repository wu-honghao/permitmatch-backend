export function getSkillKey(skill: string): string {
  return normalizeSkill(skill).toLowerCase();
}

// 标准化技能成规范的名字
export function normalizeSkill(skill: string): string {
  const key = skill.trim().toLowerCase();

  return skillAliases.get(key) ?? skill.trim();
}

export const normalizeGroup = (skills: string[]) => {
  return [...new Set(skills.map(getSkillKey))]
    .sort()
    .join("|");
};